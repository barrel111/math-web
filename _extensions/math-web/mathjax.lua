local directory = debug.getinfo(1, "S").source:sub(2):match("^(.*[/\\])") or "./"
local quote = dofile(directory .. "javascript.lua").quote
local json = dofile(directory .. "json.lua")
local M = {}

local configuration_template = [=[// Generated by math-web; load before the MathJax script.
(function () {
  const config = globalThis.MathJax = globalThis.MathJax || {};
  config.chtml = Object.assign({matchFontHeight: false}, config.chtml || {});
  const tex = config.tex = config.tex || {};
  const macros = JSON.parse(%s);
  tex.macros = Object.assign(Object.create(null), tex.macros || {}, macros);
})();
]=]

local function sorted_names(definitions)
  local names = {}
  for name in pairs(definitions) do names[#names + 1] = name end
  table.sort(names)
  return names
end

local function replacement_body(definition)
  if definition.kind ~= "operator" then return definition.body end
  local operator = definition.starred and "\\operatorname*" or "\\operatorname"
  return operator .. "{" .. definition.body .. "}"
end

local function macro_value(definition)
  local body = quote(replacement_body(definition))
  if definition.nargs == 0 then return body end

  local parts = {body, tostring(definition.nargs)}
  if definition.default ~= nil then
    parts[#parts + 1] = quote(definition.default)
  end
  return "[" .. table.concat(parts, ", ") .. "]"
end

function M.macros_json(definitions)
  local entries = {}
  for _, name in ipairs(sorted_names(definitions)) do
    local definition = definitions[name]
    if definition.kind ~= "paired" and not definition.provided then
      entries[#entries + 1] = "  " .. quote(name) .. ": " .. macro_value(definition)
    end
  end
  return "{\n" .. table.concat(entries, ",\n") .. "\n}"
end

-- JSON.parse preserves names such as '__proto__' as ordinary own properties.
-- CHTML defaults to text-sized math while preserving explicit user options.
function M.generate(definitions)
  local encoded_macros = quote(M.macros_json(definitions))
  local script = string.format(configuration_template, encoded_macros)
  local pairs, providers = {}, {}
  for _, name in ipairs(sorted_names(definitions)) do
    local definition = definitions[name]
    if definition.kind == "paired" then
      pairs[name] = {definition.opening, definition.closing, definition.body, definition.nargs}
    elseif definition.provided then
      local parameters = "[" .. definition.nargs .. "]"
      if definition.default ~= nil then parameters = parameters .. "[" .. definition.default .. "]" end
      providers[name] = "\\newcommand{\\" .. name .. "}" .. parameters .. "{" .. definition.body .. "}"
    end
  end
  local extra = json.encode({paired = pairs, providers = providers})
  return script .. string.format([=[(function () {
  const config = globalThis.MathJax;
  const tex = config.tex;
  const extra = JSON.parse(%s);
  const extensions = ['boldsymbol', 'mathtools'];
  const packages = ['base', 'ams', 'newcommand', 'configmacros', ...extensions];
  const loader = config.loader = config.loader || {};
  loader.load = [...new Set([...(loader.load || []), ...extensions.map(name => '[tex]/' + name)])];
  if (Array.isArray(tex.packages)) {
    tex.packages = [...new Set([...tex.packages, ...packages])];
  } else {
    tex.packages = tex.packages || {};
    tex.packages['[+]'] = [...new Set([...(tex.packages['[+]'] || []), ...packages])];
    if (tex.packages['[-]']) {
      tex.packages['[-]'] = tex.packages['[-]'].filter(name => !packages.includes(name));
    }
  }
  if (Object.keys(extra.paired).length) {
    tex.mathtools = tex.mathtools || {};
    tex.mathtools.pairedDelimiters = Object.assign(Object.create(null), tex.mathtools.pairedDelimiters || {}, extra.paired);
  }
  if (Object.keys(extra.providers).length) {
    tex.preFilters = [...(tex.preFilters || []), ({math, data}) => {
      let preamble = '';
      for (const [name, declaration] of Object.entries(extra.providers)) {
        if (!data.handlers.get('macro').contains(name) && !data.handlers.get('delimiter').contains(name)) {
          preamble += declaration;
        }
      }
      math.math = preamble + math.math;
    }];
  }
})();
]=], quote(extra))
end

return M
