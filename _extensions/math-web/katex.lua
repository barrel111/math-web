local directory = debug.getinfo(1, "S").source:sub(2):match("^(.*[/\\])") or "./"
local quote = dofile(directory .. "javascript.lua").quote
local json = dofile(directory .. "json.lua")
local extract = dofile(directory .. "extract.lua")
local M = {}

local configuration_template = [=[// Generated by math-web; load before Quarto's KaTeX renderer.
(function () {
const preamble = %s;
%s
})();
]=]

local function sorted_names(definitions)
  local names = {}
  for name in pairs(definitions) do names[#names + 1] = name end
  table.sort(names)
  return names
end

local function replacement_body(definition)
  if definition.kind ~= "operator" then return definition.body end
  local operator = definition.starred and "\\operatorname*" or "\\operatorname"
  return operator .. "{" .. definition.body .. "}"
end

local function alphabetic_suffix(index)
  local suffix = ""
  repeat
    index = index - 1
    suffix = string.char(97 + index % 26) .. suffix
    index = math.floor(index / 26)
  until index == 0
  return suffix
end

local function optional_helper_name(index, definitions)
  local name = "mathweb@optional@" .. alphabetic_suffix(index)
  while definitions[name] do name = name .. "x" end
  return name
end

local function parameter_list(first, last)
  local parameters = {}
  for index = first, last do
    parameters[#parameters + 1] = "#" .. index
  end
  return table.concat(parameters)
end

local function declare_macro(name, parameters, body)
  return string.format("\\def\\%s%s{%s}", name, parameters, body)
end

local function replace_delimsize(body, replacement)
  local parts, position = {}, 1
  while position <= #body do
    if body:sub(position, position) == "\\" then
      local name, after = extract.extract_cmd_name(body, position)
      if name then
        parts[#parts + 1] = name == "delimsize" and replacement or body:sub(position, after - 1)
        position = after
      else
        parts[#parts + 1] = body:sub(position, position)
        position = position + 1
      end
    else
      parts[#parts + 1] = body:sub(position, position)
      position = position + 1
    end
  end
  return table.concat(parts)
end

local function paired_declarations(name, definition, index)
  local prefix = "mathweb@paired@" .. alphabetic_suffix(index)
  local fixed, star, option = prefix .. "fixed", prefix .. "star", prefix .. "option"
  local parameters = parameter_list(1, definition.nargs)
  local opening, closing = definition.opening .. " ", definition.closing .. " "
  local fixed_body = opening .. replace_delimsize(definition.body, "") .. closing
  local star_body = "\\mathopen{\\left" .. opening .. replace_delimsize(definition.body, "\\middle ")
    .. "\\right" .. closing .. "}\\mathclose{}"
  local declarations = {
    declare_macro(fixed, parameters, fixed_body),
    declare_macro(star, parameters, star_body),
    declare_macro(prefix .. "empty", "]", "\\" .. fixed),
  }
  local dispatch = "\\@ifnextchar]{\\" .. prefix .. "empty}{\\mathwebUnsupportedDelimiterSize}"
  for _, size in ipairs({"big", "Big", "bigg", "Bigg"}) do
    local helper = prefix .. size
    local body = "\\" .. size .. "l" .. opening
      .. replace_delimsize(definition.body, "\\" .. size .. " ") .. "\\" .. size .. "r" .. closing
    declarations[#declarations + 1] = declare_macro(helper, "\\" .. size .. "]" .. parameters, body)
    dispatch = "\\@ifnextchar\\" .. size .. "{\\" .. helper .. "}{" .. dispatch .. "}"
  end
  declarations[#declarations + 1] = declare_macro(option, "[", dispatch)
  declarations[#declarations + 1] = declare_macro(name, "", "\\@ifstar{\\" .. star
    .. "}{\\@ifnextchar[{\\" .. option .. "}{\\" .. fixed .. "}}")
  return declarations
end

local function provide_macro(name, nargs, body)
  return string.format("\\providecommand{\\%s}[%d]{%s}", name, nargs, body)
end

local function optional_declarations(name, definition, helper_name)
  local helper_command = "\\" .. helper_name
  local parameters = "[#1]" .. parameter_list(2, definition.nargs)
  local helper = declare_macro(helper_name, parameters, replacement_body(definition))
  local dispatch = string.format("\\@ifnextchar[{%s}{%s[{%s}]}",
    helper_command, helper_command, definition.default)
  local command = definition.provided and provide_macro(name, 0, dispatch) or declare_macro(name, "", dispatch)
  return helper, command
end

-- Explicit def parameters preserve declared arity, even for unused arguments.
function M.preamble(definitions)
  local declarations = {}
  for index, name in ipairs(sorted_names(definitions)) do
    local definition = definitions[name]
    if definition.kind == "paired" then
      for _, declaration in ipairs(paired_declarations(name, definition, index)) do
        declarations[#declarations + 1] = declaration
      end
    elseif definition.default ~= nil then
      local helper_name = optional_helper_name(index, definitions)
      local helper, command = optional_declarations(name, definition, helper_name)
      declarations[#declarations + 1] = helper
      declarations[#declarations + 1] = command
    else
      local parameters = parameter_list(1, definition.nargs)
      if definition.provided then
        declarations[#declarations + 1] = provide_macro(name, definition.nargs, replacement_body(definition))
      else
        declarations[#declarations + 1] = declare_macro(name, parameters, replacement_body(definition))
      end
    end
  end
  return table.concat(declarations, "\n")
end

local function read_runtime()
  local file = assert(io.open(directory .. "katex-runtime.js", "rb"))
  local runtime = file:read("*a")
  file:close()
  return runtime
end

function M.generate(definitions)
  local encoded_preamble = quote(M.preamble(definitions))
  local provided_names = {}
  for name, definition in pairs(definitions) do
    if definition.provided then provided_names[#provided_names + 1] = "\\" .. name end
  end
  local runtime = "const providedNames = new Set(" .. json.encode(provided_names) .. ");\n" .. read_runtime()
  return string.format(configuration_template, encoded_preamble, runtime)
end

return M
