local t = dofile("tests/testlib.lua")
local parser = dofile("_extensions/math-web/parse.lua")
local mappings = dofile("_extensions/math-web/mappings.lua")
local function parse(source)
  local definitions, message = parser.parse(source, "preamble.sty")
  assert(definitions, message)
  return definitions
end
local function rejects(name, source, expected)
  t.test(name, function()
    local definitions, message, report = parser.parse(source, "preamble.sty")
    t.equal(definitions, nil)
    assert(message:find(expected, 1, true), message)
    t.equal(report.complete, false)
    t.equal(report.diagnostics[1].source, "preamble.sty")
  end)
end

t.test("notation fixtures parse together", function()
  local definitions, message, report = parser.parse_files({"tests/fixtures/sample-preamble/math-core.sty", "tests/fixtures/sample-preamble/math-prob.sty"})
  assert(definitions, message)
  t.equal(report.complete, true)
  t.equal(#report.packages, 9)
  t.equal(#report.metadata, 4)
  local count = 0
  for _ in pairs(definitions) do count = count + 1 end
  t.equal(count, 44)
  t.equal(definitions.fmapsto.default, "")
  t.equal(definitions.fmapsto.nargs, 2)
  t.equal(definitions.fmapsto.body, [[\xmapsto[#1]{\mkern8mu #2\mkern8mu}]])
  t.equal(definitions.paddedxmapsto, nil)
  t.equal(definitions.funcmapsto, nil)
  t.equal(definitions.set.kind, "paired")
  t.equal(definitions.set.nargs, 2)
  t.equal(definitions.set.opening, [[\lbrace]])
  t.equal(definitions.symbf.provided, true)
end)
t.test("metadata consumes optional release requirements without emitting macros", function()
  local definitions, message, report = parser.parse([[
\NeedsTeXFormat{LaTeX2e}[2020/10/01]
\ProvidesPackage{notation}[2026/10/27 notes]
\RequirePackage{amsmath, mathtools}[2020/01/01]
\newcommand{\x}{x}]], "metadata.sty")
  assert(definitions, message)
  t.equal(definitions.x.body, "x")
  t.equal(report.packages[2].name, "mathtools")
  t.equal(report.packages[2].release, "2020/01/01")
end)
t.test("provide preserves earlier imported declarations", function()
  local definitions = parse([[\newcommand{\f}{old}\providecommand{\f}[1]{#1}\providecommand{\g}[1][x]{#1}]])
  t.equal(definitions.f.body, "old")
  t.equal(definitions.f.column, 1)
  t.equal(definitions.g.provided, true)
  t.equal(definitions.g.default, "x")
end)
t.test("relax reset allows new declarations and forces provided fallback", function()
  local definitions = parse([[\newcommand{\f}{old}\let\f=\relax\newcommand{\f}{new}\let\symbf\relax\providecommand{\symbf}{x}]])
  t.equal(definitions.f.body, "new")
  t.equal(definitions.symbf.provided, nil)
end)
t.test("explicit aliases become definitions without changing the input map", function()
  local definitions = parse([[\newcommand{\label}{\customstyle{x}}]])
  local mapped = assert(mappings.apply(definitions, {customstyle = "mathrm"}))
  t.equal(mapped.customstyle.body, [[\mathrm]])
  t.equal(definitions.customstyle, nil)
end)
t.test("mappings do not overwrite imported definitions or accept TeX bodies", function()
  t.equal(mappings.apply(parse([[\newcommand{\f}{x}]]), {f = "g"}), nil)
  t.equal(mappings.apply({}, {f = [[\mathbf{#1}]]}), nil)
  t.equal(mappings.apply({}, {f = "f"}), nil)
end)
t.test("mapping names must be unique after removing their leading backslash", function()
  for _, target in ipairs({"mathrm", "mathsf"}) do
    local definitions, message = mappings.apply({}, {foo = "mathrm", ["\\foo"] = target})
    t.equal(definitions, nil)
    t.equal(message, "duplicate mapping for command \\foo")
  end
end)
rejects("missing metadata group", [[\NeedsTeXFormat]], "didn't find")
rejects("unclosed metadata optional argument", [[\ProvidesPackage{f}[oops]], "matching")
rejects("other TeX formats are not silently accepted", [[\NeedsTeXFormat{Other}]], "unsupported TeX format")
t.test("unknown packages warn without blocking declarations", function()
  local definitions, message, report = parser.parse([[\RequirePackage{unknown-package}\newcommand{\x}{x}]], "preamble.sty")
  assert(definitions, message)
  t.equal(report.complete, true)
  t.equal(report.warnings[1].kind, "unresolved package dependency")
  t.equal(report.packages[1].status, "unresolved package dependency")
end)
t.test("external options are recorded with warnings", function()
  local definitions, message, report = parser.parse([[\RequirePackage[bad]{amsmath}]], "preamble.sty")
  assert(definitions, message)
  t.equal(report.packages[1].options, "bad")
  t.equal(report.warnings[1].kind, "unhandled package options")
end)
rejects("empty package in list", [[\RequirePackage{amsmath,}]], "empty name")
rejects("arbitrary let aliases remain unsupported", [[\let\f\g]], "only")
rejects("paired declaration star rejected", [[\DeclarePairedDelimiter*{\f}{(}{)}]], "declaration star")
rejects("invalid paired arity", [[\DeclarePairedDelimiterX{\f}[10]{(}{)}{x}]], "argument count")
rejects("invalid paired parameters", [[\DeclarePairedDelimiterX{\f}[1]{(}{)}{#2}]], "parameter reference")
rejects("duplicate paired definition", [[\newcommand{\f}{x}\DeclarePairedDelimiter{\f}{(}{)}]], "duplicate definition")
t.finish()
