t.test("document-command fixture lowers to existing macro representation", function()
  local definitions, err = parser.parse_file("tests/fixtures/document-commands/macros.sty")
  assert(definitions, err)
  t.equal(definitions.DocRR.nargs, 0)
  t.equal(definitions.docpair.nargs, 2)
  t.equal(definitions.first.nargs, 2)
  t.equal(definitions.first.body, "#1")
  t.equal(definitions.shift.nargs, 2)
  t.equal(definitions.shift.default, "x")
  t.equal(definitions.emptyDefault.default, "")
  t.equal(definitions.groupDefault.default, "{x+y}")
