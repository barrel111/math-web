local t = dofile("tests/testlib.lua")
local parser = dofile("_extensions/math-web/parse.lua")
local function parse(source)
  local definitions, err = parser.parse(source, "test.sty")
  assert(definitions, err)
  return definitions
end
local function rejects(name, source, message)
  t.test(name, function()
    local definitions, err = parser.parse(source, "test.sty")
    t.equal(definitions, nil)
    assert(err:find(message, 1, true), err)
    assert(err:match("^test%.sty:%d+:%d+:"), err)
  end)
end

t.test("fixture declarations and nested replacement bodies", function()
  local definitions, err = parser.parse_file("tests/fixtures/declarations/macros.sty")
  assert(definitions, err)
  local names = {}
  for name in pairs(definitions) do names[#names + 1] = name end
  table.sort(names)
  t.equal(table.concat(names, ","), "RR,argmaxop,bare,choice,joined,literalBraces,pair,percent,rankop,spaced,unused,withDefault")
  t.equal(definitions.RR.body, [[\mathbb{R}]])
  t.equal(definitions.pair.nargs, 2)
  t.equal(definitions.pair.body, [[\left\langle #1,\frac{#2}{2}\right\rangle]])
  t.equal(definitions.choice.body, "new")
  t.equal(definitions.rankop.kind, "operator")
  t.equal(definitions.rankop.starred, false)
  t.equal(definitions.argmaxop.starred, true)
  t.equal(definitions.withDefault.nargs, 2)
  t.equal(definitions.withDefault.default, "x")
  t.equal(definitions.bare.body, "b")
  t.equal(definitions.literalBraces.body, [[\{#1\}]])
  t.equal(definitions.percent.body, [[50\%]])
  t.equal(definitions.joined.body, "a+b")
  t.equal(definitions.spaced.body, "\n  \\frac{#1}{2}\n")
end)
t.test("empty and comments-only input", function()
  t.equal(next(parse("")), nil)
  t.equal(next(parse("% \\newcommand{\\hidden}{bad}")), nil)
end)
t.test("empty bodies and empty optional defaults", function()
  local definitions = parse([[\newcommand{\empty}{}\newcommand{\optional}[1][]{#1}]])
  t.equal(definitions.empty.body, "")
  t.equal(definitions.optional.default, "")
end)
t.test("braced bracket in optional default", function()
  t.equal(parse([[\newcommand{\f}[1][{x]y}]{#1}]]).f.default, "{x]y}")
end)
t.test("starred declarations and control symbols", function()
  local definitions = parse([[\newcommand*\f[1]{#1}\renewcommand*{\f}{x}\newcommand{\!}{z}]])
  t.equal(definitions.f.body, "x")
  t.equal(definitions.f.nargs, 0)
  t.equal(definitions.f.starred, true)
  t.equal(definitions["!"].body, "z")
end)
t.test("comment removal respects escaped percent and slash parity", function()
  local definitions = parse("\\newcommand{\\f}{a\\%b\\\\% discarded\r\n  c}")
  t.equal(definitions.f.body, "a\\%b\\\\c")
end)
t.test("comments between declaration tokens", function()
  local definitions = parse("\\newcommand% comment\n{\\f}% comment\n[1]% comment\n{#1}")
  t.equal(definitions.f.nargs, 1)
end)
t.test("comments preserve control-word boundaries", function()
  t.equal(parse("\\newcommand{\\f}{\\alpha% comment\n x}").f.body, "\\alpha x")
  local definitions, err = parser.parse("\\new% comment\ncommand{\\f}{x}")
  t.equal(definitions, nil)
  assert(err:find("unsupported top-level command \\new", 1, true), err)
end)
t.test("source locations survive removed comments", function()
  local definitions = parse("% comment\n\n  \\newcommand{\\f}{x}")
  t.equal(definitions.f.line, 3)
  t.equal(definitions.f.column, 3)
  local result, err = parser.parse("% comment\n\n  \\newcommand{\\f}", "broken.sty")
  t.equal(result, nil)
  assert(err:find("broken.sty:3:3:", 1, true), err)
end)
t.test("replacement bodies are not scanned as declarations", function()
  local definitions = parse([[\newcommand{\outer}{\newcommand{\inner}{x}}]])
  t.equal(definitions.inner, nil)
  t.equal(definitions.outer.body, [[\newcommand{\inner}{x}]])
end)
t.test("endinput stops scanning", function()
  local definitions = parse([[\newcommand{\f}{x}\endinput invalid text]])
  t.equal(definitions.f.body, "x")
end)
t.test("escaped hashes and doubled parameter markers", function()
  t.equal(parse([[\newcommand{\f}[1]{\# #1 ##1}]]).f.body, [[\# #1 ##1]])
end)
t.test("nine arguments", function()
  t.equal(parse([[\newcommand{\f}[9]{#9}]]).f.nargs, 9)
end)
t.test("missing input file", function()
  local definitions, err = parser.parse_file("tests/fixtures/no-such-file.sty")
  t.equal(definitions, nil)
  assert(err:find("no-such-file.sty", 1, true), err)
end)
