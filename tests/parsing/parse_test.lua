local base = "tests/fixtures/multiple-files/base.sty"
local extra = "tests/fixtures/multiple-files/extra.sty"
t.test("ordered files preserve definition origins and final renewal", function()
  local definitions, err = parser.parse_files({base, extra})
  assert(definitions, err)
  t.equal(definitions.RR.source, base)
  t.equal(definitions.RR.line, 1)
  t.equal(definitions.choice.body, "new")
  t.equal(definitions.choice.source, extra)
  t.equal(definitions.choice.line, 1)
  t.equal(definitions.domain.body, [[\RR^2]])
end)
t.test("declaration state never leaks between parse operations", function()
  assert(parser.parse_files({base, extra}))
  local definitions, err = parser.parse_file(extra)
  t.equal(definitions, nil)
  assert(err:find("cannot renew undefined", 1, true), err)
  t.equal(parser.parse_file(base).choice.body, "old")
end)
t.test("reversed files fail at the original location", function()
  local definitions, err = parser.parse_files({extra, base})
  t.equal(definitions, nil)
  assert(err:find(extra .. ":1:1: cannot renew undefined", 1, true), err)
end)
t.test("missing later file never returns partial definitions", function()
  local definitions, err = parser.parse_files({base, "absent-math-web.sty"})
  t.equal(definitions, nil)
  assert(err:find("absent-math-web.sty", 1, true), err)
  assert(parser.parse_files({base, extra}))
end)
t.test("empty file lists and blank paths are rejected", function()
  t.equal(parser.parse_files({}), nil)
  t.equal(parser.parse_files({" "}), nil)
end)
t.finish()
