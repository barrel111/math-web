t.test("unbraced document-command names and signature whitespace", function()
  local definitions = parse("\\NewDocumentCommand\\f{ O {\\frac{1}{2}} \n m }{#1+#2}")
  t.equal(definitions.f.nargs, 2)
  t.equal(definitions.f.default, [[\frac{1}{2}]])
end)
t.test("document commands replace classic definitions and vice versa", function()
  local definitions = parse([[\newcommand{\f}{x}\RenewDocumentCommand{\f}{m}{#1}\renewcommand{\f}{z}]])
  t.equal(definitions.f.body, "z")
  t.equal(definitions.f.nargs, 0)
end)
t.test("optional-only and maximum arity document signatures", function()
  local definitions = parse([[\NewDocumentCommand{\f}{O{x}}{#1}\NewDocumentCommand{\g}{O{}mmmmmmmm}{#9}]])
  t.equal(definitions.f.nargs, 1)
  t.equal(definitions.g.nargs, 9)
end)
